"""Generate a book of Chess960 positions with material handicaps (~1 knight).

    python harness/nnue/handicap960_book.py --out E:/machete/books/handicap960.epd --count 20000
    python harness/nnue/handicap960_book.py --out E:/machete/books/equal960.epd --count 20000 --equal

Chess960 back ranks (positions 0..959), castling rights removed (-).
Handicaps are removed from a random side (White or Black) with equal probability:
  1. A knight
  2. A bishop
  3. 3 non-center pawns (from files a, b, c, f, g, h)
  4. 2 pawns including at least one center pawn (d or e)

After removing the handicap, K random legal plies are played (--plies K, default 2).
"""

import argparse
import collections
import random
import sys

import chess


def make_position(rng, plies=2, equal=False):
    pos_num = rng.randint(0, 959)
    b = chess.Board.from_chess960_pos(pos_num)
    b.set_castling_fen("-")
    handicap_type = "equal"
    side_str = "none"

    if not equal:
        side = rng.choice([chess.WHITE, chess.BLACK])
        side_str = "white" if side == chess.WHITE else "black"
        h_choice = rng.choice(["knight", "bishop", "3_non_center_pawns", "2_pawns_one_center"])
        handicap_type = h_choice

        if h_choice == "knight":
            knights = list(b.pieces(chess.KNIGHT, side))
            if knights:
                b.remove_piece_at(rng.choice(knights))
        elif h_choice == "bishop":
            bishops = list(b.pieces(chess.BISHOP, side))
            if bishops:
                b.remove_piece_at(rng.choice(bishops))
        elif h_choice == "3_non_center_pawns":
            non_center = [sq for sq in b.pieces(chess.PAWN, side) if chess.square_file(sq) not in (3, 4)]
            if len(non_center) >= 3:
                for sq in rng.sample(non_center, 3):
                    b.remove_piece_at(sq)
        elif h_choice == "2_pawns_one_center":
            center = [sq for sq in b.pieces(chess.PAWN, side) if chess.square_file(sq) in (3, 4)]
            if center:
                c_sq = rng.choice(center)
                b.remove_piece_at(c_sq)
                rem = list(b.pieces(chess.PAWN, side))
                if rem:
                    b.remove_piece_at(rng.choice(rem))

    # Play K random legal plies
    for _ in range(plies):
        if b.is_game_over():
            return None, None, None
        legal = list(b.legal_moves)
        if not legal:
            return None, None, None
        b.push(rng.choice(legal))

    if b.is_game_over():
        return None, None, None

    # Castling rights remain '-'
    b.set_castling_fen("-")
    return b.fen(), handicap_type, side_str


def main():
    parser = argparse.ArgumentParser(description="Generate Chess960 handicap/equal starting books")
    parser.add_argument("--out", required=True, help="Output EPD file path")
    parser.add_argument("--count", type=int, default=20000, help="Number of unique positions to generate")
    parser.add_argument("--plies", type=int, default=2, help="Number of random plies from start (default: 2)")
    parser.add_argument("--equal", action="store_true", help="Generate equal Chess960 starts without handicaps")
    parser.add_argument("--seed", type=int, default=1, help="Random seed")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    seen = set()
    positions = []
    stats_h = collections.Counter()
    stats_side = collections.Counter()

    attempts = 0
    max_attempts = args.count * 10
    while len(positions) < args.count and attempts < max_attempts:
        attempts += 1
        fen, h_type, side_str = make_position(rng, plies=args.plies, equal=args.equal)
        if fen is None or fen in seen:
            continue
        seen.add(fen)
        positions.append(fen)
        stats_h[h_type] += 1
        stats_side[side_str] += 1

    with open(args.out, "w", encoding="utf-8", newline="\n") as out:
        out.write("# Chess960 %s book generated by harness/nnue/handicap960_book.py\n" %
                  ("equal" if args.equal else "handicap (~1 knight)"))
        out.write("# total: %d positions, plies: %d, seed: %d\n" % (len(positions), args.plies, args.seed))
        out.write("# handicap types: %s\n" % dict(stats_h))
        out.write("# handicap sides: %s\n" % dict(stats_side))
        out.write("# castling: '-'\n")
        for fen in positions:
            out.write(fen + "\n")

    print("Wrote %d unique positions to %s" % (len(positions), args.out))
    print("Handicap breakdown:", dict(stats_h))
    print("Side breakdown:", dict(stats_side))
    return 0


if __name__ == "__main__":
    sys.exit(main())
